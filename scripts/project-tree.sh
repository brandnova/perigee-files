#!/usr/bin/env bash
# Regenerates PROJECT_TREE.md: every file Git tracks, plus untracked files that aren't ignored.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
{
  echo "# Project file tree"
  echo
  echo "Files that are tracked, or not ignored by .gitignore. Generated by scripts/project-tree.sh on $(date +%F)."
  echo
  echo '```text'
  git ls-files --cached --others --exclude-standard | grep -v '^PROJECT_TREE.md$' | sort | awk -F/ '
    { path = ""
      for (i = 1; i <= NF; i++) {
        path = path (i > 1 ? "/" : "") $i
        if (i < NF) { if (!(path in seen)) { seen[path] = 1; printf "%*s%s/\n", (i - 1) * 2, "", $i } }
        else printf "%*s%s\n", (i - 1) * 2, "", $i
      } }'
  echo '```'
} > PROJECT_TREE.md
echo "wrote PROJECT_TREE.md"